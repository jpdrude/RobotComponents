"""Build / check the page index of ABB's RAPID manuals (docs/data/abb-pages.yml).

The wiki links ABB's manuals directly (never copies them). Pages link to the exact page of an
instruction with the [[abb:MoveL]] shortcode (see tools/docs/rc_links.py), which needs the page
numbers. They come from the PDFs' own bookmarks.

    python tools/docs/abb_pages.py            # download the manuals, rewrite docs/data/abb-pages.yml
    python tools/docs/abb_pages.py --check    # fail if links are broken or the manuals changed

Run --check before every publish (the Docs workflow does). If it fails, ABB has published a new
revision: run without --check, review the diff of abb-pages.yml, and commit it.
The PDFs are only downloaded to a temporary folder and never stored in the repository.
"""

import argparse
import re
import sys
import tempfile
import urllib.request
from pathlib import Path

import yaml
from pypdf import PdfReader

DATA = Path(__file__).resolve().parents[2] / "docs" / "data" / "abb-pages.yml"
URL = "https://search.abb.com/library/Download.aspx?DocumentID={id}&LanguageCode=en&DocumentPartId=&Action=Launch"
MANUALS = {
    "ifd": ("3HAC050917-001", "Technical reference manual - RAPID Instructions, Functions and Data types"),
    "overview": ("3HAC050947-001", "Technical reference manual - RAPID overview"),
    "kernel": ("3HAC050946-001", "Technical reference manual - RAPID kernel"),
}
NUMBER = re.compile(r"^\d+(\.\d+)*\s+")


def download(doc_id: str, folder: Path) -> tuple[Path, str]:
    """Download a manual; returns the file and the PDF's own address.

    ABB's Download.aspx link redirects (302) to a signed address of the PDF. Browsers lose the
    #page=N jump on that redirect and open the cover page, so page links point to the PDF
    itself: the redirect target without the expiring ?x-sign=... part (it works unsigned).
    That address changes with every revision, which --check then reports.
    """
    target = folder / f"{doc_id}.pdf"
    req = urllib.request.Request(URL.format(id=doc_id), headers={"User-Agent": "Mozilla/5.0 (RobotComponents wiki link check)"})
    with urllib.request.urlopen(req, timeout=300) as resp:
        if resp.status != 200 or "pdf" not in resp.headers.get("Content-Type", ""):
            raise RuntimeError(f"{doc_id}: HTTP {resp.status}, {resp.headers.get('Content-Type')}")
        target.write_bytes(resp.read())
        pdf_url = resp.geturl().split("?")[0]
    check = urllib.request.Request(pdf_url, headers={"User-Agent": "Mozilla/5.0 (RobotComponents wiki link check)", "Range": "bytes=0-99"})
    with urllib.request.urlopen(check, timeout=60) as resp:
        if "pdf" not in resp.headers.get("Content-Type", ""):
            raise RuntimeError(f"{doc_id}: {pdf_url} does not serve the PDF without signature ({resp.headers.get('Content-Type')})")
    return target, pdf_url


def index(pdf: Path, numbered_only: bool) -> dict:
    reader = PdfReader(str(pdf))
    pages: dict[str, int] = {}

    def walk(items, depth):
        for item in items:
            if isinstance(item, list):
                walk(item, depth + 1)
                continue
            title = item.title.strip()
            if depth > 2 or (numbered_only and not NUMBER.match(title)):
                continue  # instructions manual: only numbered entries (instructions, functions, data types)
            name = NUMBER.sub("", title).split(" - ")[0].strip()
            pages.setdefault(name, reader.get_destination_page_number(item) + 1)

    walk(reader.outline, 0)
    revision = None
    for page in reader.pages[:4]:
        found = re.search(r"Revision:\s*([A-Z0-9]+)", page.extract_text() or "")
        if found:
            revision = found.group(1)
            break
    return {"revision": revision, "page_count": len(reader.pages), "pages": dict(sorted(pages.items(), key=lambda kv: kv[0].lower()))}


def build() -> dict:
    out = {}
    with tempfile.TemporaryDirectory() as tmp:
        for key, (doc_id, title) in MANUALS.items():
            pdf, pdf_url = download(doc_id, Path(tmp))
            info = index(pdf, numbered_only=(key == "ifd"))
            # url: stable link to the whole manual; pdf: the PDF itself, used for #page=N links
            out[key] = {"document": doc_id, "title": title, "url": URL.format(id=doc_id), "pdf": pdf_url, **info}
            print(f"{key}: {doc_id} revision {info['revision']}, {info['page_count']} pages, {len(info['pages'])} entries")
    return out


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="compare with the committed file instead of writing it")
    args = parser.parse_args()
    fresh = build()
    if not args.check:
        header = "# Generated by tools/docs/abb_pages.py from the bookmarks of ABB's manuals. Do not edit by hand.\n"
        DATA.write_text(header + yaml.safe_dump(fresh, sort_keys=False, allow_unicode=True), encoding="utf-8")
        print(f"wrote {DATA}")
        return 0
    committed = yaml.safe_load(DATA.read_text(encoding="utf-8"))
    problems = []
    for key, now in fresh.items():
        old = committed.get(key, {})
        if old.get("pdf") != now["pdf"]:
            problems.append(f"{key}: PDF address changed {old.get('pdf')} -> {now['pdf']}")
        if old.get("revision") != now["revision"] or old.get("page_count") != now["page_count"]:
            problems.append(f"{key}: revision {old.get('revision')} -> {now['revision']}, pages {old.get('page_count')} -> {now['page_count']}")
        moved = [n for n, p in old.get("pages", {}).items() if now["pages"].get(n) != p]
        if moved:
            problems.append(f"{key}: {len(moved)} entries moved or disappeared, e.g. {moved[:5]}")
    if problems:
        print("ABB manuals changed since abb-pages.yml was generated:\n  " + "\n  ".join(problems))
        print("Run `python tools/docs/abb_pages.py`, review the diff and commit it.")
        return 1
    print("ABB links OK: all manuals reachable, revisions and page numbers unchanged.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
